"""The .arch.py format: parse (web-tree-sitter), render (deterministic), load and write."""

__module__ = "sketch"
__paths__ = ["src/sketch/**"]
__depends_on__ = ["core", "fs"]

class LoadedSketch(Protocol):
    file: string
    module: ArchModule
    text: string

class ParseResult(Protocol):
    errors: 'SketchError[]'
    module: ArchModule | null

class SketchError(Protocol):
    column: number
    file: string
    line: number
    message: string

class SketchSet(Protocol):
    broken: 'string[]'
    errors: 'SketchError[]'
    missing: boolean
    sketches: 'LoadedSketch[]'

class PySyntaxError(Error):
    node: Readonly[Node]
    def __init__(self, message: string, node: Node): ...

def colonRow(def_: Node) -> number: ...
def dedentDocstring(raw: string) -> string: ...
def defLine(name: string, sig: Signature, self: string | null = ...) -> string: ...
def fieldLine(field: FieldMember) -> string: ...
def getGoParser() -> Promise[Parser]: ...
def getPythonParser() -> Promise[Parser]: ...
def isDocstring(node: Node) -> boolean: ...
def isOverloaded(stmt: Node) -> boolean: ...
def kids(node: Node) -> 'Node[]': ...

async def loadSketches(
    root: string,
    sketchDir: string,
    cache: ArchlockCache = ...,
) -> Promise[SketchSet]: ...

def memberLines(member: Member) -> 'string[]': ...
def named(node: Node) -> 'Node[]': ...
def param(n: Node) -> Param: ...
async def parseSketch(text: string, file: string) -> Promise[ParseResult]: ...
def renderDocstring(raw: string, indent: string) -> string: ...
def renderFieldName(name: string) -> string: ...
def renderParam(p: Param) -> string: ...

# invariant: deterministic; renderSketch(parse(x)) === x for every sketch archlock writes
def renderSketch(mod: ArchModule) -> string: ...

def renderSymbolText(sym: ArchSymbol) -> string: ...
def renderTypeParam(param: string) -> string: ...
def sketchPath(sketchDir: string, module: string) -> string: ...
def sortMembers(members: 'Member[]') -> 'Member[]': ...
def splitDecorated(stmt: Node) -> '{ def: Node; decorators: Node[] }': ...
def symbolLines(sym: ArchSymbol) -> 'string[]': ...
def typeAliasParams(typeNode: Node) -> 'Node[] | null': ...
def typeOf(node: Node) -> string: ...
def typeParam(node: Node) -> string: ...
def typeParams(def_: Node) -> 'string[]': ...
def unwrapType(node: Node) -> Node: ...
def unwrapWrapper(node: Node, wrapper: string) -> Node | null: ...
def writeText(root: string, relPath: string, text: string) -> void: ...

