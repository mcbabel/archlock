import { decodePythonString } from "../core/canonical.js";
import { type ArchModule, compareNames } from "../core/model.js";
import { compressionLine } from "./format.js";
import { mermaidGraph } from "./graph.js";

export const PROJECT_URL = "https://github.com/mcbabel/archlock";

/** First line of a module docstring, without quotes. */
export function docSummary(mod: ArchModule): string {
  const raw = mod.soft.docstring;
  if (raw === null) return "";
  const text = decodePythonString(raw) ?? raw;
  return (text.trim().split("\n")[0] ?? "").trim();
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

/** `archlock/README.md`, regenerated by `init` and `accept`. Deterministic. */
export function renderReadme(
  modules: ArchModule[],
  codeLines: number,
  sketchLines: number,
): string {
  const sorted = [...modules].sort((a, b) => compareNames(a.name, b.name));
  const rows = sorted.map((m) => {
    const deps = m.dependsOn.length > 0 ? [...m.dependsOn].sort(compareNames).join(", ") : "–";
    return `| [${m.name}](./${m.name}.arch.py) | ${cell(docSummary(m)) || "–"} | ${m.symbols.length} | ${cell(deps)} |`;
  });
  return [
    "<!-- Generated by archlock. Do not edit by hand: `archlock accept` rewrites this file. -->",
    "",
    "# Architecture",
    "",
    `This folder is the architecture lockfile of this repository, maintained with [archlock](${PROJECT_URL}).`,
    "Each `*.arch.py` file sketches one module: which files belong to it, which modules it may depend on,",
    "and its public API. CI runs `archlock check`, so every architecture change is visible and deliberate.",
    "",
    `**${compressionLine(codeLines, sketchLines)}**`,
    "",
    "```mermaid",
    mermaidGraph(sorted).trimEnd(),
    "```",
    "",
    "| Module | Description | Public symbols | Depends on |",
    "|---|---|---|---|",
    ...rows,
    "",
    "To change the design, edit a sketch and run `archlock push` to let your coding agent update the code.",
    "To adopt an intended code change, run `archlock accept`.",
    "",
  ].join("\n");
}
