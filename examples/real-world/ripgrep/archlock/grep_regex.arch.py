class ErrorKind(Clone, Debug, Enum):
    Regex = '(String)'
    NotAllowed = '(String)'
    InvalidLineTerminator = '(u8)'
    Banned = '(u8)'

class Error(Clone, Debug, 'std::error::Error', 'std::fmt::Display'):
    def kind(self) -> '&ErrorKind': ...

class RegexCaptures(Captures, Clone, Debug): ...

class RegexMatcher(Clone, Debug, Matcher):
    @staticmethod
    def new(pattern: '&str') -> Result[RegexMatcher, Error]: ...
    @staticmethod
    def new_line_matcher(pattern: '&str') -> Result[RegexMatcher, Error]: ...

class RegexMatcherBuilder(Clone, Debug, Default):
    def ban_byte(self, byte: Option[u8]) -> '&mut RegexMatcherBuilder': ...
    def build(self, pattern: '&str') -> Result[RegexMatcher, Error]: ...
    def build_literals[B: AsRef[str]](self, literals: '&[B]') -> Result[RegexMatcher, Error]: ...
    def build_many[P: AsRef[str]](self, patterns: '&[P]') -> Result[RegexMatcher, Error]: ...
    def case_insensitive(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def case_smart(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def crlf(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def dfa_size_limit(self, bytes: usize) -> '&mut RegexMatcherBuilder': ...
    def dot_matches_new_line(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def fixed_strings(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def ignore_whitespace(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def line_terminator(self, line_term: Option[u8]) -> '&mut RegexMatcherBuilder': ...
    def multi_line(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def nest_limit(self, limit: u32) -> '&mut RegexMatcherBuilder': ...
    @staticmethod
    def new() -> RegexMatcherBuilder: ...
    def octal(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def size_limit(self, bytes: usize) -> '&mut RegexMatcherBuilder': ...
    def swap_greed(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def unicode(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def whole_line(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
    def word(self, yes: bool) -> '&mut RegexMatcherBuilder': ...
