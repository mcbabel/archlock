class ByteSet(Clone, Debug):
    def add(self: '&mut Self', byte: u8): ...
    def add_all(self: '&mut Self', start: u8, end: u8): ...
    def contains(self, byte: u8) -> bool: ...
    @staticmethod
    def empty() -> ByteSet: ...
    @staticmethod
    def full() -> ByteSet: ...
    def remove(self: '&mut Self', byte: u8): ...
    def remove_all(self: '&mut Self', start: u8, end: u8): ...

class LineTerminator(Clone, Copy, Debug, Default, Eq, Hash, PartialEq):
    def as_byte(self) -> u8: ...
    def as_bytes(self) -> '&[u8]': ...
    @staticmethod
    def byte(byte: u8) -> LineTerminator: ...
